#!/bin/sh
# Первичная настройка распакованной поставки LocalRAG.
#
# Zip из Jenkins (Java-реализация) не хранит unix-права: без +x не запускаются
# ни демон, ни лаунчер моста, и оба отказа молчаливые.
#
# Запускать из каталога распаковки через интерпретатор — свой +x файл теряет так же:
#
#     sh setup.sh
#
# Переменные:
#   MCP_CONFIG=<путь>       один конкретный конфиг агента вместо всех известных
#   MCP_AGENT=<имя>         имя агента для MCP_CONFIG (умолчание custom): по нему
#                           мост находит свой токен, без него демон ответит 401
#   SKIP_MCP_REGISTER=1     не трогать конфиг агента (и токенов не будет)
set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
# Чей токен показать в подсказке curl ниже; при штатной регистрации — wsc.
AGENT=wsc
if [ -n "${MCP_CONFIG:-}" ]; then
    AGENT=${MCP_AGENT:-custom}
fi

restore() {
    if [ ! -f "$1" ]; then
        echo "  ПРОПУЩЕН, файла нет: $1" >&2
        return 0
    fi
    if [ -x "$1" ]; then
        echo "  уже исполняемый: $1"
    else
        chmod +x "$1"
        echo "  восстановлен +x: $1"
    fi
}

echo "Права после распаковки:"
restore "$DIR/main/main"
restore "$DIR/mcp/mcp_launcher.sh"

echo
if [ "${SKIP_MCP_REGISTER:-0}" = "1" ]; then
    echo "Регистрация MCP-моста пропущена (SKIP_MCP_REGISTER=1)."
elif ! command -v python3 >/dev/null 2>&1; then
    # Мост на чистом stdlib ради системного python3; без него работают демон и HTTP API.
    echo "python3 не найден: MCP-мост запускать нечем, регистрация пропущена." >&2
else
    echo "Регистрация MCP-моста в конфигах агентов:"
    if [ -n "${MCP_CONFIG:-}" ]; then
        python3 "$DIR/mcp/register_mcp.py" --config "$MCP_CONFIG" --agent "$AGENT" \
            || echo "  не удалось — пропишите вручную, см. mcp/README.md" >&2
    else
        python3 "$DIR/mcp/register_mcp.py" \
            || echo "  не удалось — пропишите вручную, см. mcp/README.md" >&2
    fi
fi

cat <<EOF

Дальше вручную:

  1. Запустить демон (RAG_PORT=0 — порт выберет ядро и опубликует его сам):

       CONFIG_PATH=$DIR/cfg/distro.yml RAG_HOST=127.0.0.1 RAG_PORT=0 \\
         $DIR/main/main > /tmp/rag.log 2>&1 &

     Первый прогрев модели — 40-45 секунд, до этого сервис не отвечает.

  2. Проверить готовность:

       curl -s http://127.0.0.1:\$(cat ~/.files-search/port)/api/v1/health

  3. По умолчанию индексируется весь /home (cfg/distro.yml). Сузить набор
     папок — через API. Правкой YAML не выйдет: сохранённый
     ~/.ragsearch/user_conf.yml (если он есть) главнее списка из YAML, а
     снятые папки удаляет из индекса только POST /api/v1/config.
     Все ручки, кроме /health, требуют токен агента: регистрация выше кладёт
     его каждому агенту с найденным конфигом в ~/.files-search/tokens/
     (ниже — $AGENT; нет такого файла — возьмите токен другого агента).
     Заголовок — из файла, а не в командной строке: так токен не виден в
     списке процессов (нужен bash или zsh):

       curl -X POST http://127.0.0.1:\$(cat ~/.files-search/port)/api/v1/config \\
         -H @<(printf 'Authorization: Bearer %s' "\$(cat ~/.files-search/tokens/$AGENT.token)") \\
         -H 'Content-Type: application/json' \\
         -d "{\\"folders\\":[\\"\$HOME/Документы\\"]}"

  4. Индексация уже идёт: демон в поставке стартует её сам (бесшовный режим),
     команда activate не нужна. Ход — GET /api/v1/status, готовность —
     is_indexing: false. Остановить на сессию, сохранив индекс, —
     POST /api/v1/deactivate (после перезапуска демона индексация
     возобновится).

  5. Перезапустить агента, чтобы он подхватил инструменты.

Чего в этой поставке НЕТ — в отличие от пакета .deb:

  - демон не поднимается сам ни при входе в сессию, ни после перезагрузки;
  - регистрация MCP сделана ОДИН раз, только что. Если агент перезапишет свой
    конфиг (например, при установке или обновлении приложения), запись
    пропадёт — придётся запустить setup.sh заново. В пакете это чинят
    .path-юниты, которые следят за конфигами агентов;
  - в конфиг агента уехал путь ВНУТРЬ этого каталога:
        $DIR/mcp/mcp_launcher.sh
    Перенесёте или удалите каталог — агент молча останется без инструментов.

Целевая поставка — пакет .deb (БТ §4.1: предустановленный системный пакет
вместе с образом ОС). Этот архив — для быстрой проверки и разработки.

Удаление: sh $DIR/uninstall.sh
EOF
